def _iso(dt: datetime) -> str:
    return dt.isoformat()


def _trace(base: datetime, node: str, minutes: float, summary: str) -> dict:
    return {"node": node, "timestamp": _iso(base + timedelta(minutes=minutes)), "summary": summary}


def _seed_one(
    *,
    doc_id: str,
    client_id: str,
    original_filename: str,
    doc_type: str,
    schema_name: str,
    confidence: float,
    extracted_fields: dict,
    human_decision: str,
    human_feedback: str,
    days_ago: float,
    review_delay_minutes: float,
) -> None:
    with SessionLocal() as db:
        if db.get(Document, doc_id) is not None:
            print(f"[skip] document {doc_id!r} already seeded")
            return

    flags = cross_check_document(client_id, doc_type, extracted_fields)
    t0 = datetime.now(timezone.utc) - timedelta(days=days_ago)

    if human_decision == "reject":
        final_status, status = "rejected", "rejected"
    else:
        final_status, status = "added_to_organizer", "completed"

    trace = [
        _trace(t0, "ingest", 0.0, f"Detected PDF; extracted text from {original_filename}."),
        _trace(t0, "classify", 0.3, f"Classified as {doc_type!r} (confidence={confidence:.2f})."),
        _trace(t0, f"extract_{doc_type.lower().replace('-', '')}", 0.6, f"Extracted fields using {schema_name}."),
        _trace(t0, "cross_check", 0.8, f"{len(flags)} flag(s) found."),
        _trace(t0, "review", review_delay_minutes, f"Preparer decision={human_decision} | {human_feedback[:200]}"),
        _trace(t0, "finalize", review_delay_minutes + 0.1, f"Document finalized with status={final_status}."),
    ]
    state_snapshot = {
        "doc_type": doc_type,
        "classification_confidence": confidence,
        "extraction_schema_used": schema_name,
        "extracted_fields": extracted_fields,
        "cross_check_flags": flags,
        "human_decision": human_decision,
        "human_feedback": human_feedback,
        "final_status": final_status,
        "status": status,
    }

    doc = Document(
        id=doc_id,
        client_id=client_id,
        original_filename=original_filename,
        doc_type=doc_type,
        classification_confidence=confidence,
        status=status,
        final_status=final_status,
        extracted_fields=extracted_fields,
        cross_check_flags=flags,
        trace=trace,
        state_snapshot=state_snapshot,
        error=None,
        created_at=t0,
        updated_at=t0 + timedelta(minutes=review_delay_minutes + 0.1),
    )
    with SessionLocal() as db:
        db.add(doc)
        db.commit()
    print(f"[seeded] document {doc_id!r} ({doc_type}, {final_status})")


