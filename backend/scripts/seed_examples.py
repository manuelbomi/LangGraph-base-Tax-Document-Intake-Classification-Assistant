"""Seed realistic, complete example documents into the `documents` table for
the two bundled fictitious clients (Jordan Ellis, Morgan Alvarez).

These are hand-authored (not generated by a live LLM call, to keep this
repo's setup free to run) but the classification/extraction VALUES are fed
through the real, deterministic `app/tools/organizer.py::cross_check_document`
and `recompute_client_completeness` functions -- exactly what the live graph
calls -- so the cross-check flags and organizer completeness shown are
authentic, not hand-typed guesses. They exist so the "Client Organizer /
Example Analyses" page has real, varied content (including a deliberately
INCOMPLETE client and a caught duplicate) before a visitor uploads anything
themselves.

Run with:
    python -m scripts.seed_examples

Requires `scripts/seed_clients.py` to have already run (the clients this
script attaches documents to must already exist).
"""
